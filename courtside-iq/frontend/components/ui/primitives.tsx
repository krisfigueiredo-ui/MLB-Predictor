/* ---------------- Tooltip ---------------- */
export function Tip({ content, children, side = "top" }: { content: React.ReactNode; children: React.ReactNode; side?: "top" | "bottom" | "left" | "right" }) {
  return (
    <TooltipPrimitive.Provider delayDuration={150}>
      <TooltipPrimitive.Root>
        <TooltipPrimitive.Trigger asChild>
          <span className="inline-flex">{children}</span>
        </TooltipPrimitive.Trigger>
        <TooltipPrimitive.Portal>
          <TooltipPrimitive.Content
            side={side}
            sideOffset={6}
            className="z-[80] max-w-xs rounded-lg border border-line bg-ink-800 px-3 py-2 text-xs leading-relaxed text-mist-300 shadow-panel"
          >
            {content}
          </TooltipPrimitive.Content>
        </TooltipPrimitive.Portal>
      </TooltipPrimitive.Root>
    </TooltipPrimitive.Provider>
  );
}

/* ---------------- Stats ---------------- */
export function Stat({
  label,
  value,
  sub,
  tone,
  className,
  hint,
}: {
  label: React.ReactNode;
  value: React.ReactNode;
  sub?: React.ReactNode;
  tone?: "gain" | "loss" | "volt" | "flare" | "cyan";
  className?: string;
  hint?: React.ReactNode;
}) {
  const color = tone === "gain" ? "text-gain" : tone === "loss" ? "text-loss" : tone === "volt" ? "text-volt-300" : tone === "flare" ? "text-flare" : tone === "cyan" ? "text-cyan" : "text-mist";
  return (
    <div className={cn("min-w-0", className)}>
      <div className="label flex items-center gap-1">
        {label}
        {hint && (
          <Tip content={hint}>
            <Info className="h-3 w-3 text-mist-500" />
          </Tip>
        )}
      </div>
      <div className={cn("mt-1 font-display text-2xl font-semibold tabular tracking-tight", color)}>{value}</div>
      {sub && <div className="mt-0.5 text-xs text-mist-400">{sub}</div>}
    </div>
  );
}

export function ProbBar({
  left,
  right,
  leftLabel,
  rightLabel,
  leftColor = "#2F7BFF",
  rightColor = "#22D3EE",
  push = 0,
  className,
}: {
  left: number;
  right: number;
  leftLabel?: React.ReactNode;
  rightLabel?: React.ReactNode;
  leftColor?: string;
  rightColor?: string;
  push?: number;
  className?: string;
}) {
  return (
    <div className={cn("w-full", className)}>
      {(leftLabel || rightLabel) && (
        <div className="mb-1 flex justify-between text-[11px] font-medium tabular text-mist-300">
          <span>{leftLabel}</span>
          <span>{rightLabel}</span>
        </div>
      )}
      <div className="flex h-1.5 w-full overflow-hidden rounded-full bg-ink-700">
        <div style={{ width: `${left * 100}%`, background: leftColor }} className="transition-all duration-700" />
        {push > 0 && <div style={{ width: `${push * 100}%` }} className="bg-gold/70" />}
        <div style={{ width: `${right * 100}%`, background: rightColor }} className="transition-all duration-700" />
      </div>
    </div>
  );
}

export function Meter({ value, max = 1, color = "#2F7BFF", className }: { value: number; max?: number; color?: string; className?: string }) {
  return (
    <div className={cn("h-1.5 w-full overflow-hidden rounded-full bg-ink-700", className)}>
      <div className="h-full rounded-full transition-all duration-700" style={{ width: `${Math.max(0, Math.min(1, value / max)) * 100}%`, background: color }} />
    </div>
  );
}

