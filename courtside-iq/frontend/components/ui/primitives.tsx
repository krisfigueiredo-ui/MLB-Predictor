export function DemoBadge({ show = true, className }: { show?: boolean; className?: string }) {
  if (!show) return null;
  return (
    <Tip content="Synthetic demo data generated by the COURTSIDE simulator. Not real games, statistics or sportsbook prices.">
      <Badge tone="flare" className={className}>
        <FlaskConical className="h-3 w-3" /> Demo
      </Badge>
    </Tip>
  );
}

export function ResultBadge({ result }: { result: string }) {
  const tone = result === "win" ? "gain" : result === "loss" ? "loss" : result === "push" ? "gold" : result === "void" ? "neutral" : "volt";
  return <Badge tone={tone as any}>{result}</Badge>;
}

/* ---------------- Button ---------------- */
const buttonVariants = cva(
  "inline-flex items-center justify-center gap-2 whitespace-nowrap rounded-lg text-sm font-medium transition-all focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-volt/60 disabled:pointer-events-none disabled:opacity-50",
  {
    variants: {
      variant: {
        primary: "bg-volt text-white shadow-glow hover:bg-volt-400",
        ghost: "text-mist-300 hover:bg-ink-700 hover:text-mist",
        outline: "border border-line bg-ink-850 text-mist-300 hover:border-volt/50 hover:text-mist",
        danger: "border border-loss/40 bg-loss/10 text-loss hover:bg-loss/20",
      },
      size: { sm: "h-8 px-3 text-xs", md: "h-9 px-4", icon: "h-8 w-8" },
    },
    defaultVariants: { variant: "outline", size: "md" },
  },
);

export const Button = React.forwardRef<
  HTMLButtonElement,
  React.ButtonHTMLAttributes<HTMLButtonElement> & VariantProps<typeof buttonVariants> & { asChild?: boolean }
>(({ className, variant, size, asChild, ...p }, ref) => {
  const C: any = asChild ? Slot : "button";
  return <C ref={ref} className={cn(buttonVariants({ variant, size }), className)} {...p} />;
});
Button.displayName = "Button";

/* ---------------- Segmented / Tabs ---------------- */
export function Segmented<T extends string>({
  value,
  onChange,
  options,
  className,
  size = "md",
}: {
  value: T;
  onChange: (v: T) => void;
  options: { value: T; label: React.ReactNode }[];
  className?: string;
  size?: "sm" | "md";
}) {
  return (
    <div role="tablist" className={cn("inline-flex rounded-lg border border-line bg-ink-900/80 p-0.5", className)}>
      {options.map((o) => (
        <button
          key={o.value}
          role="tab"
          aria-selected={value === o.value}
          onClick={() => onChange(o.value)}
          className={cn(
            "rounded-md font-medium transition-all",
            size === "sm" ? "px-2.5 py-1 text-[11px]" : "px-3 py-1.5 text-xs",
            value === o.value ? "bg-volt/15 text-volt-300 shadow-[inset_0_0_0_1px_rgba(47,123,255,0.35)]" : "text-mist-400 hover:text-mist",
          )}
        >
          {o.label}
        </button>
      ))}
    </div>
  );
}

